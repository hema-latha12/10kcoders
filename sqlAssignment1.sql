SELECT ename FROM emp WHERE job IN ('clerk', 'salesman', 'analyst') AND sal > 2500;

-- 11. DISPLAY THE LIST OF EMPLOYEES WHO HAVE JOINED A COMPANY BEFORE 1980 OR AFTER 1988.
