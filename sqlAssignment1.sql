-- 5. WAQTD NAMES STARTS WITH VOWELS AND ENDS WITH CONSONANTS.
SELECT ename FROM emp WHERE ename REGEXP '^[aeiou].*[b-df-hj-np-tv-z]$';

-- 6. WAQTD NAMES OF EMPLOYESS WHO WORKING AS A MANAGER.
